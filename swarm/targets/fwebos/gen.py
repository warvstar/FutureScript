def lit(v):
    if v is None:
        return "nil"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, str):
        return '"' + v.replace("\\", "\\\\").replace('"', '\\"').replace("{", "\\{").replace("\n", "\\n").replace("\t", "\\t") + '"'
    if isinstance(v, list):
        return "[" + ", ".join(lit(x) for x in v) + "]"
    raise TypeError(v)


HELPERS = {
    "acceptSh": "fn acceptSh(os, line) {\n  var r = sh(os, line)\n  return [r.out, r.err, r.code]\n}\n",
    "acceptSyntax": "fn acceptSyntax(os, line) {\n  var r = sh(os, line)\n  return r.code == 2 && r.out == \"\" && r.err.find(\"sh: syntax error: \") == 0\n}\n",
    "acceptTick": "fn acceptTick(os, ms) {\n  var r = tick(os, ms)\n  return [r.out, r.err]\n}\n",
    "acceptWins": "fn acceptWins(os) {\n  var r = []\n  for w in wmList(os) { r.push([w.id, w.app, w.title, w.x, w.y, w.w, w.h, w.focused, w.minimized, w.maximized]) }\n  return r\n}\n",
    "acceptCursor": "fn acceptCursor(os, t) {\n  var c = termCursor(os, t)\n  return [c.row, c.col]\n}\n",
}


def header(body):  # only the helpers a file uses: a file must compile with just the API its tests call
    return ("// generated by gen.py from its reference implementation of the spec; do not edit\nimport \"../src/os.fut\"\n" +
            "".join("\n" + h for k, h in HELPERS.items() if k + "(" in body))


def test(name, lines):
    return "\ntest " + lit(name) + " {\n" + "".join("  " + l + "\n" for l in lines) + "}\n"


class Syn(str):
    pass


class Tick(int):
    pass


def sh_steps(o, steps, var="os"):
    body = []
    for s in steps:
        if isinstance(s, Syn):
            r = o.sh(s)
            assert r["code"] == 2 and r["out"] == "" and r["err"].startswith("sh: syntax error: "), (s, r)
            body.append("expect acceptSyntax(%s, %s)" % (var, lit(str(s))))
        elif isinstance(s, Tick):
            r = o.tick(int(s))
            body.append("expect acceptTick(%s, %d) == %s" % (var, s, lit([r["out"], r["err"]])))
        else:
            r = o.sh(s)
            body.append("expect acceptSh(%s, %s) == %s" % (var, lit(s), lit([r["out"], r["err"], r["code"]])))
    return body


def sht(name, steps):
    o = OS()
    return test(name, ["var os = boot()"] + sh_steps(o, steps))


